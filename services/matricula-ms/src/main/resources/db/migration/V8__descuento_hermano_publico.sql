-- =====================================================================
-- Descuento por hermano en la matrícula en línea del sitio público.
-- La familia declara los datos del hermano y sube sus documentos (constancia de matrícula, DNI, etc.); la secretaría los revisa y confirma el
-- descuento (la solicitud vive en pago-ms). Los archivos son pocos y pequeños (máx. 3 de 3 MB), así que se guardan aquí, junto al trámite.
-- =====================================================================
ALTER TABLE matriculas_publicas
    ADD COLUMN hermano_documento    VARCHAR(20),
    ADD COLUMN hermano_nombre       VARCHAR(220),
    ADD COLUMN hermano_descuento_id BIGINT;

CREATE TABLE evidencias_hermano (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT       NOT NULL REFERENCES matriculas (id),
    nombre       VARCHAR(150) NOT NULL,
    tipo         VARCHAR(30)  NOT NULL,     -- application/pdf | image/jpeg | image/png (según el contenido real, no el nombre)
    tamano       INTEGER      NOT NULL,
    contenido    BYTEA        NOT NULL,
    subido_en    TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_evid_hermano_matricula ON evidencias_hermano (matricula_id);
