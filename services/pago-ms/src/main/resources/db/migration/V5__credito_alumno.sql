-- Crédito del alumno: lo que la familia deposita por adelantado. Cada depósito suma al crédito; cuando una pensión vence se cobra
-- sola del crédito (si no alcanza, la cuota queda con lo que falte; si sobra, el resto sigue como crédito).
CREATE TABLE creditos_alumno (
    alumno_id      BIGINT        PRIMARY KEY,
    saldo          NUMERIC(10,2) NOT NULL DEFAULT 0,
    actualizado_en TIMESTAMP     NOT NULL DEFAULT now(),
    version        BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_credito_saldo CHECK (saldo >= 0)
);

-- Libro de movimientos: el monto siempre es positivo y el tipo dice si suma o resta.
--   DEPOSITO (suma) · COBRO_CUOTA (resta) · REVERSION (suma: se anuló un cobro hecho con crédito) · ANULACION (resta: se anuló un depósito)
CREATE TABLE movimientos_credito (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id       BIGINT        NOT NULL,
    tipo            VARCHAR(12)   NOT NULL,
    monto           NUMERIC(10,2) NOT NULL,
    saldo_despues   NUMERIC(10,2) NOT NULL,
    medio           VARCHAR(15),
    referencia      VARCHAR(80),
    cuota_id        BIGINT        REFERENCES cuotas(id),
    pago_id         BIGINT        REFERENCES pagos(id),
    caja_sesion_id  BIGINT        REFERENCES cajas_sesion(id),
    anula_a         BIGINT        REFERENCES movimientos_credito(id),
    anulado         BOOLEAN       NOT NULL DEFAULT FALSE,
    detalle         VARCHAR(200),
    registrado_por  BIGINT,
    creado_en       TIMESTAMP     NOT NULL DEFAULT now(),
    idempotency_key VARCHAR(80),
    CONSTRAINT ck_mov_credito_tipo  CHECK (tipo IN ('DEPOSITO','COBRO_CUOTA','REVERSION','ANULACION')),
    CONSTRAINT ck_mov_credito_monto CHECK (monto > 0),
    CONSTRAINT ck_mov_credito_medio CHECK (medio IS NULL OR medio IN ('EFECTIVO','TARJETA','YAPE_PLIN','TRANSFERENCIA'))
);
CREATE INDEX idx_mov_credito_alumno ON movimientos_credito (alumno_id, creado_en DESC);
CREATE INDEX idx_mov_credito_caja   ON movimientos_credito (caja_sesion_id) WHERE caja_sesion_id IS NOT NULL;
CREATE UNIQUE INDEX uk_mov_credito_idem ON movimientos_credito (idempotency_key) WHERE idempotency_key IS NOT NULL;

-- Un cobro hecho con el crédito del alumno es un pago más (medio CREDITO), sin caja.
ALTER TABLE pagos DROP CONSTRAINT ck_pago_medio;
ALTER TABLE pagos ADD CONSTRAINT ck_pago_medio CHECK (medio IN ('EFECTIVO','TARJETA','YAPE_PLIN','TRANSFERENCIA','ONLINE_SIMULADO','CREDITO'));
