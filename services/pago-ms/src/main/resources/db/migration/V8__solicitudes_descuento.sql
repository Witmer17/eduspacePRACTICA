-- =====================================================================
-- Solicitudes de descuento de la matrícula (p. ej. hermanos)
-- La familia (o la secretaría) pide un descuento; hasta que la SECRETARÍA lo prueba la matrícula no se puede pagar ni generar. Al aprobar se
-- asigna el descuento al alumno y se recalcula la cuota de matrícula (solo si todavía no tiene pagos).
-- =====================================================================
CREATE TABLE solicitudes_descuento (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id         BIGINT       NOT NULL,
    matricula_id      BIGINT       NOT NULL,
    descuento_id      BIGINT       NOT NULL REFERENCES descuentos(id),
    anio_id           BIGINT       NOT NULL,
    motivo            VARCHAR(300) NOT NULL,
    hermano_alumno_id BIGINT,
    estado            VARCHAR(10)  NOT NULL DEFAULT 'PENDIENTE',
    solicitada_por    BIGINT,
    solicitada_en     TIMESTAMP    NOT NULL DEFAULT now(),
    resuelta_por      BIGINT,
    resuelta_en       TIMESTAMP,
    motivo_resolucion VARCHAR(300),
    CONSTRAINT ck_sol_desc_estado CHECK (estado IN ('PENDIENTE','APROBADA','RECHAZADA'))
);
-- Una sola solicitud en revisión por matrícula
CREATE UNIQUE INDEX uk_sol_desc_pendiente ON solicitudes_descuento (matricula_id) WHERE estado = 'PENDIENTE';
CREATE INDEX idx_sol_desc_estado ON solicitudes_descuento (estado, solicitada_en);
