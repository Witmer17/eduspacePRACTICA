-- Reparto del dinero de caja entre las áreas de trabajo del colegio.
-- Cada fila es un movimiento: monto > 0 sale de caja hacia el área; monto < 0 vuelve a caja.
-- El dinero asignado a un área es la suma de sus movimientos; el disponible en caja es lo cobrado (pagos CONFIRMADO) menos todo lo asignado.
-- area_id es el id del área en planificacion-ms (número simple, sin relación entre bases).
CREATE TABLE asignaciones_area (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id     BIGINT         NOT NULL,
    monto       NUMERIC(12, 2) NOT NULL,
    saldo_area  NUMERIC(12, 2) NOT NULL,
    motivo      VARCHAR(255),
    creado_por  BIGINT,
    creado_en   TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_asignacion_monto CHECK (monto <> 0),
    CONSTRAINT ck_asignacion_saldo CHECK (saldo_area >= 0)
);
CREATE INDEX idx_asignaciones_area ON asignaciones_area (area_id, id DESC);

