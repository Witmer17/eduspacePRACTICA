-- =====================================================================
-- Órdenes de pago de la matrícula (pasarela simulada, con el mismo ciclo que una real)
--   1) el SERVIDOR crea la orden con lo que falta de la matrícula (el navegador nunca elige el monto);
--   2) la pasarela cobra y avisa con su id de transacción y un estado;
--   3) el servidor confirma UNA sola vez (idempotente por transacción): suma el dinero al crédito del alumno
--      y cobra la matrícula de ese crédito, lo que genera la matrícula.
-- =====================================================================
CREATE TABLE ordenes_pago (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(40)   NOT NULL,
    alumno_id       BIGINT        NOT NULL,
    matricula_id    BIGINT        NOT NULL,
    monto           NUMERIC(10,2) NOT NULL,
    estado          VARCHAR(10)   NOT NULL DEFAULT 'PENDIENTE',
    creada_por      BIGINT,
    creada_en       TIMESTAMP     NOT NULL DEFAULT now(),
    expira_en       TIMESTAMP     NOT NULL,
    transaccion_id  VARCHAR(60),
    medio           VARCHAR(15),
    pagador         VARCHAR(200),
    respuesta       VARCHAR(200),
    confirmada_en   TIMESTAMP,
    pago_id         BIGINT,
    CONSTRAINT uk_orden_codigo UNIQUE (codigo),
    CONSTRAINT ck_orden_monto CHECK (monto > 0),
    CONSTRAINT ck_orden_estado CHECK (estado IN ('PENDIENTE','APROBADA','RECHAZADA','EXPIRADA'))
);
-- Una misma transacción de la pasarela no se aplica dos veces
CREATE UNIQUE INDEX uk_orden_transaccion ON ordenes_pago (transaccion_id) WHERE transaccion_id IS NOT NULL;
-- Una sola orden vigente por matrícula
CREATE UNIQUE INDEX uk_orden_pendiente ON ordenes_pago (matricula_id) WHERE estado = 'PENDIENTE';
CREATE INDEX idx_orden_alumno ON ordenes_pago (alumno_id, creada_en DESC);
