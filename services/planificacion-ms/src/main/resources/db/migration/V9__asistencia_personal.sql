-- Asistencia diaria del personal del colegio (una fila por persona y día). Sin fila = día sin marcar.
CREATE TABLE asistencia_personal (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personal_id  BIGINT      NOT NULL,
    fecha        DATE        NOT NULL,
    estado       VARCHAR(20) NOT NULL,
    hora_entrada TIME,
    hora_salida  TIME,
    observacion  VARCHAR(255),
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_asistencia_personal FOREIGN KEY (personal_id) REFERENCES docentes (id),
    CONSTRAINT uk_asistencia_personal_dia UNIQUE (personal_id, fecha),
    CONSTRAINT ck_asistencia_horas CHECK (hora_salida IS NULL OR hora_entrada IS NULL OR hora_salida >= hora_entrada)
);
CREATE INDEX idx_asistencia_personal_fecha ON asistencia_personal (fecha);
