-- Contratos y pagos del personal (recursos humanos). Cuelgan de docentes, que es el registro de todo el personal.
CREATE TABLE contratos_personal (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personal_id   BIGINT         NOT NULL,
    tipo          VARCHAR(30)    NOT NULL,
    cargo         VARCHAR(100),
    fecha_inicio  DATE           NOT NULL,
    fecha_fin     DATE,
    remuneracion  NUMERIC(12, 2) NOT NULL,
    estado        VARCHAR(20)    NOT NULL DEFAULT 'VIGENTE',
    fecha_rescision DATE,
    motivo_rescision VARCHAR(255),
    observaciones VARCHAR(500),
    creado_en     TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_contrato_personal FOREIGN KEY (personal_id) REFERENCES docentes (id),
    CONSTRAINT ck_contrato_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
    CONSTRAINT ck_contrato_remuneracion CHECK (remuneracion >= 0)
);
CREATE INDEX idx_contratos_personal ON contratos_personal (personal_id);

CREATE TABLE pagos_personal (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personal_id   BIGINT         NOT NULL,
    contrato_id   BIGINT,
    periodo       VARCHAR(7)     NOT NULL,
    concepto      VARCHAR(20)    NOT NULL,
    descripcion   VARCHAR(200),
    monto         NUMERIC(12, 2) NOT NULL,
    estado        VARCHAR(20)    NOT NULL DEFAULT 'PENDIENTE',
    fecha_pago    DATE,
    medio         VARCHAR(30),
    referencia    VARCHAR(100),
    creado_en     TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pago_personal FOREIGN KEY (personal_id) REFERENCES docentes (id),
    CONSTRAINT fk_pago_contrato FOREIGN KEY (contrato_id) REFERENCES contratos_personal (id),
    CONSTRAINT ck_pago_monto CHECK (monto > 0)
);
CREATE INDEX idx_pagos_personal ON pagos_personal (personal_id);
CREATE INDEX idx_pagos_periodo ON pagos_personal (periodo);
