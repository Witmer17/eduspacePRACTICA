-- Pabellones del colegio: los nombra el usuario (A, B, «Central»…) y declara cuántas aulas tiene cada uno.
-- Un aula puede pertenecer a un pabellón; el servicio no deja registrar más aulas que las declaradas.
CREATE TABLE pabellones (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(30) NOT NULL,
    cantidad_aulas SMALLINT    NOT NULL DEFAULT 0,
    CONSTRAINT ck_pabellon_cantidad CHECK (cantidad_aulas >= 0)
);
CREATE UNIQUE INDEX uk_pabellon_nombre ON pabellones (lower(nombre));

ALTER TABLE aulas ADD COLUMN pabellon_id BIGINT;
ALTER TABLE aulas ADD CONSTRAINT fk_aula_pabellon FOREIGN KEY (pabellon_id) REFERENCES pabellones (id);
CREATE INDEX idx_aulas_pabellon ON aulas (pabellon_id);
