-- Áreas de trabajo del colegio: todo el personal (docente o no) pertenece a una. La tabla docentes pasa a ser el registro de personal;
-- solo el área DOCENCIA puede dictar cursos o ser tutor (lo exige el servicio), así que el armado de horarios no cambia.
CREATE TABLE areas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(30)  NOT NULL,
    nombre      VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    activo      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_area_codigo UNIQUE (codigo)
);

