-- Cuentas donde se le deposita el pago a cada persona del personal (banco, billetera o caja). Una persona puede tener varias; una sola es la principal.
CREATE TABLE cuentas_deposito_personal (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personal_id BIGINT       NOT NULL,
    banco       VARCHAR(30)  NOT NULL,
    tipo        VARCHAR(15)  NOT NULL,
    numero      VARCHAR(20)  NOT NULL,
    cci         VARCHAR(20),
    titular     VARCHAR(150) NOT NULL,
    principal   BOOLEAN      NOT NULL DEFAULT FALSE,
    activo      BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cuenta_deposito_personal FOREIGN KEY (personal_id) REFERENCES docentes (id) ON DELETE CASCADE,
    CONSTRAINT ck_cuenta_numero CHECK (numero ~ '^[0-9]{8,20}$'),
    CONSTRAINT ck_cuenta_cci CHECK (cci IS NULL OR cci ~ '^[0-9]{20}$'),
    CONSTRAINT ck_cuenta_tipo CHECK (tipo IN ('AHORROS', 'CORRIENTE', 'SUELDO', 'BILLETERA'))
);
CREATE INDEX idx_cuentas_deposito_personal ON cuentas_deposito_personal (personal_id);
-- No se repite la misma cuenta activa de una persona, y solo una activa es la principal.
CREATE UNIQUE INDEX uk_cuenta_deposito_activa ON cuentas_deposito_personal (personal_id, banco, numero) WHERE activo;
CREATE UNIQUE INDEX uk_cuenta_deposito_principal ON cuentas_deposito_personal (personal_id) WHERE principal AND activo;
